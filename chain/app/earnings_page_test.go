func citationsTable() string {
	rows := make([][]string, len(earningsCitations))
	for i, c := range earningsCitations {
		path := "chain/" + c.file
		if rest, ok := strings.CutPrefix(c.file, "../"); ok {
			path = rest
		}
		rows[i] = []string{c.what, fmt.Sprintf("`%s:%d`", path, c.line)}
	}
	return table([]string{"Number", "Where it is set"}, rows...)
}

func earningsPageBlock() string {
	return earningsStartMark + "\n\n" +
		"### What each share can pay in one epoch (ORAMA)\n\n" + perEpochPools() + "\n" +
		"### Validators and delegators, per epoch (ORAMA)\n\n" + validatorTable() + "\n" +
		"### Storage providers, per epoch (ORAMA)\n\n" + storageTable() + "\n" +
		"### Relays, per epoch (ORAMA)\n\n" + relayTable() + "\n" +
		"### Epochs per day\n\n" + perDayTable() + "\n" +
		"### Where each number comes from\n\n" + citationsTable() + "\n" +
		earningsEndMark
}

func TestEarningsPage_tablesMatchTheParameters(t *testing.T) {
	want := earningsPageBlock()
	page, err := os.ReadFile(earningsPagePath)
	require.NoError(t, err)
	text := string(page)
	start, end := strings.Index(text, earningsStartMark), strings.Index(text, earningsEndMark)
	require.True(t, start >= 0 && end > start, "the page needs its generated block between %q and %q", earningsStartMark, earningsEndMark)
	end += len(earningsEndMark)

	if *updateEarningsPage {
		require.NoError(t, os.WriteFile(earningsPagePath, []byte(text[:start]+want+text[end:]), 0o644))
		return
	}
	require.Equal(t, want, text[start:end], "the what-do-i-earn tables are out of date with the parameters: run go test ./app -run TestEarningsPage -update-earnings-page")
}

func TestEarningsPage_numbersFollowTheCodeNotTheProse(t *testing.T) {
	// The first row of the first table is epoch 1: 14,848 ORAMA split 60/25/10/5.
	split := emissiontypes.SplitEpochMint(emissiontypes.MaxMintableForEpoch(1))
	require.Equal(t, "8,908.8", orama(split.Validator))
	require.Equal(t, "3,712", orama(split.Storage))
	require.Equal(t, "1,484.8", orama(split.Relay))
	require.Equal(t, "742.4", orama(split.Development))
	require.Equal(t, "0.0000009", orama(math.NewInt(900)))

	// The operator cap binds the large operator and hands the excess to the others.
	large, small, rest := validatorShares()
	require.Equal(t, powertypes.DefaultParams().CapFractionNormal.String(), large.String())
	require.True(t, rest.GT(math.LegacyNewDecWithPrec(1816, 5)), "the redistribution raises each average operator above its raw 1.816%%")
	require.True(t, small.GT(math.LegacyNewDecWithPrec(1, 2)), "the redistribution raises the small operator above its raw 1%%")

	// A relay at the per-relay cap, and the exit relay at the per-operator cap.
	rp := relaytypes.DefaultParams()
	require.Equal(t, "100", orama(rp.PerRelayCap))
	require.Equal(t, "200", orama(rp.PerOperatorCap))
}

func TestEarningsPage_everyCitationStillPointsAtItsNumber(t *testing.T) {
	for _, c := range earningsCitations {
		// A file of core is read through chain/testdata/repo, which links it
		// in, so the go test cache sees it as an input.
		path := "../" + c.file
		if rest, ok := strings.CutPrefix(c.file, "../"); ok {
			path = "../testdata/repo/" + rest
		}
		raw, err := os.ReadFile(path)
		require.NoError(t, err, c.what)
		lines := strings.Split(string(raw), "\n")
		require.GreaterOrEqual(t, len(lines), c.line, "%s: %s has %d lines", c.what, c.file, len(lines))
		require.Contains(t, lines[c.line-1], c.contains, "%s: %s:%d moved", c.what, c.file, c.line)
	}
}
